'use client';

/**
 * WhatsApp Bridge Service
 * 
 * Connects the FEI XMD WhatsApp bot (https://github.com/viztrlabs/whatsapp_bot)
 * with VizTR's messaging system. The bot runs as a separate Node.js service
 * using Baileys, and syncs messages with VizTR via webhook endpoints.
 *
 * Architecture:
 *   WhatsApp User <-> FEI XMD Bot (Baileys) <-> VizTR Webhook API <-> VizTR Database
 */

const WHATSAPP_WEBHOOK_URL =
  typeof process !== 'undefined' && process.env.NEXT_PUBLIC_SUPABASE_URL
    ? `${process.env.NEXTAUTH_URL || 'https://viztr.com'}/api/messaging/whatsapp`
    : '';

const WHATSAPP_SEND_URL =
  typeof process !== 'undefined' && process.env.NEXT_PUBLIC_SUPABASE_URL
    ? `${process.env.NEXTAUTH_URL || 'https://viztr.com'}/api/messaging/whatsapp/send`
    : '';

const WHATSAPP_WEBHOOK_SECRET = typeof process !== 'undefined' ? process.env.WHATSAPP_WEBHOOK_SECRET : '';

interface BridgeConfig {
  webhookUrl: string;
  sendUrl: string;
  webhookSecret: string | undefined;
  botName: string;
  ownerNumber: string | undefined;
}

const defaultConfig: BridgeConfig = {
  webhookUrl: WHATSAPP_WEBHOOK_URL,
  sendUrl: WHATSAPP_SEND_URL,
  webhookSecret: WHATSAPP_WEBHOOK_SECRET,
  botName: 'VizTR WhatsApp Bot',
  ownerNumber: undefined,
};

/**
 * Generates a .env file for the FEI XMD bot with VizTR branding and webhook config.
 */
export function generateBotEnv(config?: Partial<BridgeConfig>): string {
  const cfg = { ...defaultConfig, ...config };
  return `# VizTR WhatsApp Bot Configuration (FEI XMD - Rebranded)
# Generated by VizTR Settings Manager
# Connect this bot to: https://github.com/viztrlabs/whatsapp_bot

# =====================================================================
# VIZTR WHATSAPP BOT SETTINGS
# =====================================================================
BOT_NAME=VizTR Support
BOT_VERSION=1.0.0
BOT_URL=https://viztr.com
BOT_IMAGE_URL=https://viztr.com/logo.png
OWNER_NAME=VizTR Support Team
OWNER_NUMBER=${cfg.ownerNumber || 'REPLACE_WITH_YOUR_WHATSAPP_NUMBER'}
PREFIX=!

# =====================================================================
# WHATSAPP CONNECTION (Baileys)
# =====================================================================
FEI_SESSION_DIR=./auth_info_baileys
FEI_DATA_DIR=./data

# =====================================================================
# VIZTR INTEGRATION WEBHOOKS
# =====================================================================
# The bot posts incoming WhatsApp messages to this endpoint
VIZTR_WEBHOOK_URL=${cfg.webhookUrl}
VIZTR_WEBHOOK_SECRET=${cfg.webhookSecret || 'REPLACE_WITH_WEBHOOK_SECRET'}

# VizTR sends outbound replies to this endpoint for the bot to deliver
VIZTR_SEND_URL=${cfg.sendUrl}

# =====================================================================
# AI CHAT PROVIDERS (Optional - for automated responses)
# =====================================================================
# GEMINI_API_KEY=re_your_resend_key
# OPENAI_API_KEY=sk-...
# OPENROUTER_API_KEY=sk-or-v1-...

# =====================================================================
# DATABASE (Optional - PostgreSQL for bot-side persistence)
# =====================================================================
# DATABASE_URL=postgresql://...
`;

}

/**
 * Returns the webhook configuration for the bot to connect to VizTR.
 */
export function getWhatsAppBridgeConfig(): BridgeConfig {
  return { ...defaultConfig };
}

/**
 * Sends a message via the WhatsApp bot webhook.
 * This is called when an agent replies in the VizTR dashboard and
 * the message needs to be delivered via WhatsApp.
 */
export async function sendViaWhatsAppBot(
  conversationId: string,
  to: string,
  text: string
): Promise<{ success: boolean; messageId?: string; error?: string }> {
  try {
    const res = await fetch(`${WHATSAPP_SEND_URL}`, {
      method: 'PUT',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ conversationId, to, text }),
    });

    if (!res.ok) {
      const err = await res.json().catch(() => ({}));
      return { success: false, error: err?.error || `Send failed (${res.status})` };
    }

    const data = await res.json();
    return { success: true, messageId: data.messageId };
  } catch (err: any) {
    return { success: false, error: err?.message || 'Failed to send via WhatsApp bot' };
  }
}

/**
 * Checks if WhatsApp bot integration is configured.
 */
export function isWhatsAppConfigured(): boolean {
  return Boolean(WHATSAPP_WEBHOOK_URL && WHATSAPP_SEND_URL);
}

export default {
  generateBotEnv,
  getWhatsAppBridgeConfig,
  sendViaWhatsAppBot,
  isWhatsAppConfigured,
};
